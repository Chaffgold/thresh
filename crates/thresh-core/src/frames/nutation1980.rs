#[cfg(test)]
mod tests {
    use super::IAU1980_NUTATION_TERMS;

    /// Transcription tripwire: checksums computed from the fetched
    /// `liberfa/erfa src/nut80.c` table by the parse script that generated
    /// this file (run this session): Σ(integer multipliers) = 243,
    /// Σ(sp) = −184152.0, Σ(ce) = 98298.0. The `sp`/`ce` columns are
    /// integer-valued, so the `f64` sums are exact. Any dropped, duplicated,
    /// or mistyped term moves at least one of these sums.
    #[test]
    fn table_checksums_match_fetched_source() {
        let multiplier_sum: i64 = IAU1980_NUTATION_TERMS
            .iter()
            .flat_map(|(m, _)| m.iter())
            .map(|&v| i64::from(v))
            .sum();
        let sp_sum: f64 = IAU1980_NUTATION_TERMS.iter().map(|(_, c)| c[0]).sum();
        let ce_sum: f64 = IAU1980_NUTATION_TERMS.iter().map(|(_, c)| c[2]).sum();
        assert_eq!(multiplier_sum, 243);
        assert_eq!(sp_sum, -184152.0);
        assert_eq!(ce_sum, 98298.0);
    }

    /// The two largest terms (the 18.6-year Ω term and the semi-annual
    /// 2F−2D+2Ω term), spot-checked against rows 1 and 9 of the fetched
    /// `liberfa/erfa src/nut80.c` table.
    #[test]
    fn largest_terms_match_fetched_source() {
        assert_eq!(
            IAU1980_NUTATION_TERMS[0],
            ([0, 0, 0, 0, 1], [-171996.0, -174.2, 92025.0, 8.9])
        );
        assert_eq!(
            IAU1980_NUTATION_TERMS[8],
            ([0, 0, 2, -2, 2], [-13187.0, -1.6, 5736.0, -3.1])
        );
    }
}
